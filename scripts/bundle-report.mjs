#!/usr/bin/env node
/**
 * Bundle report (PLAN.md §5.5, M19). Reads the client build manifest and prints
 * — and writes to docs/bundle/m19.md — the initial-load JavaScript for the two
 * entry surfaces the budgets care about, the ten heaviest chunks (diet targets),
 * and every lazy route chunk. Run after a build:
 *
 *   npm run build && node scripts/bundle-report.mjs
 *
 * The numbers here are what scripts/bundle-budget.mjs enforces; this script is
 * the human-readable view and never fails a build.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

import {
  closureSizes,
  entryKey,
  fileSizes,
  kib,
  readManifest,
  staticClosure,
} from './lib/bundle-sizes.mjs'

const REPORT_PATH = path.join('docs', 'bundle', 'm19.md')
const HEAVIEST_COUNT = 10

const manifest = readManifest()
const entry = entryKey(manifest)

/** The initial-load set every page currently shares: the entry's static closure. */
const initial = closureSizes(manifest, entry)

/** Route chunks: dynamic entries whose src is a file under routes/. */
const routeChunks = Object.entries(manifest)
  .filter(([, chunk]) => chunk.isDynamicEntry === true && (chunk.src ?? '').includes('/routes/'))
  .map(([key, chunk]) => ({
    route: (chunk.src ?? key).replace('src/client/routes/', '').replace('?tsr-split=component', ''),
    gzip: fileSizes(chunk.file).gzip,
    // The chunk's own static closure minus what the shell already loaded: the
    // marginal cost of visiting this route once the shell is running.
    marginalGzip: marginalGzip(key),
  }))
  .toSorted((a, b) => b.marginalGzip - a.marginalGzip)

function marginalGzip(key) {
  const closure = staticClosure(manifest, key)
  let gzip = 0
  for (const chunkKey of closure) {
    if (initial.keys.has(chunkKey)) {
      continue
    }
    const chunk = manifest[chunkKey]
    if (chunk !== undefined) {
      gzip += fileSizes(chunk.file).gzip
    }
  }
  return gzip
}

/** The heaviest individual JS chunks by own gzip, wherever they sit in the graph. */
const heaviest = Object.entries(manifest)
  .filter(([, chunk]) => chunk.file.endsWith('.js'))
  .map(([, chunk]) => ({
    file: chunk.file.replace('assets/', ''),
    src: (chunk.src ?? '').replace('src/client/', ''),
    gzip: fileSizes(chunk.file).gzip,
  }))
  .toSorted((a, b) => b.gzip - a.gzip)
  .slice(0, HEAVIEST_COUNT)

const heaviestRows = heaviest.map(
  (chunk) =>
    `| ${kib(chunk.gzip)} kB | \`${chunk.file}\` | ${chunk.src === '' ? '—' : `\`${chunk.src}\``} |`,
)
const routeRows = routeChunks.map(
  (chunk) => `| ${kib(chunk.gzip)} kB | ${kib(chunk.marginalGzip)} kB | \`${chunk.route}\` |`,
)

const lines = [
  '# Bundle report (M19)',
  '',
  'Generated by `scripts/bundle-report.mjs` from `dist/client/.vite/manifest.json`.',
  'gzip is level 9; brotli is quality 11 (what the CDN serves). "Initial load"',
  'is the static-import closure of the boot entry — the JavaScript that must run',
  'before any route renders.',
  '',
  '## Initial load (shared by every page today)',
  '',
  '| Asset | gzip | brotli |',
  '| --- | --- | --- |',
  `| JavaScript (${initial.keys.size} chunks) | ${kib(initial.js.gzip)} kB | ${kib(initial.js.brotli)} kB |`,
  `| CSS (${initial.cssFiles.size}) | ${kib(initial.css.gzip)} kB | ${kib(initial.css.brotli)} kB |`,
  '',
  `## Heaviest ${HEAVIEST_COUNT} JavaScript chunks`,
  '',
  '| gzip | chunk | source |',
  '| --- | --- | --- |',
  ...heaviestRows,
  '',
  '## Route chunks (marginal cost over the shell)',
  '',
  '| gzip (own) | gzip (marginal) | route |',
  '| --- | --- | --- |',
  ...routeRows,
  '',
]

await mkdir(path.dirname(REPORT_PATH), { recursive: true })
await writeFile(REPORT_PATH, `${lines.join('\n')}\n`)

console.info(
  `initial-load JS: ${kib(initial.js.gzip)} kB gzip / ${kib(initial.js.brotli)} kB brotli`,
)
console.info(`initial-load CSS: ${kib(initial.css.gzip)} kB gzip`)
console.info(`heaviest chunk: ${heaviest[0].file} at ${kib(heaviest[0].gzip)} kB gzip`)
console.info(`report written to ${REPORT_PATH}`)
